import { flatEvents } from '../js/flat-events.js';
import { assert, test } from './runner.js';

const DATES = ['2026-10-10', '2026-10-17', '2026-10-24', '2026-10-31', '2026-11-07'];
// Группы разрядов в ru-RU разделены неразрывным пробелом — для сравнения приводим к обычному.
const plain = s => s.replace(/[  ]/g, ' ');

test('события: появление, полная цена, скидка, пропуск и возвращение — новые сверху', () => {
  const events = flatEvents({
    eff: [6000000, 6000000, 5800000, null, 5700000],
    full: [7000000, 7100000, 7100000, null, 7100000],
    area: [40, 40, 40, null, 41],
    first: 0,
  }, DATES);
  assert.deepEqual(events.map(e => [e.date, plain(e.text), e.tone, e.muted]), [
    ['2026-11-07', 'вернулась, цена −100 000 ₽ (−2%)', 'new', false],
    ['2026-10-31', 'Неизвестно', 'missing', false],
    ['2026-10-24', 'цена со скидкой −200 000 ₽ (−3%), полная не изменилась', 's1', false],
    ['2026-10-17', 'полная цена +100 000 ₽, фактическая — нет', null, true],
    ['2026-10-10', 'в первой выгрузке, 6 000 000 ₽', null, false],
  ]);
});

test('события: площадь и одинаковое изменение обеих цен; квартира, появившаяся позже', () => {
  const events = flatEvents({
    eff: [null, 5000000, 4900000, 4900000, 4900000],
    full: [null, 6000000, 5900000, 5900000, 5900000],
    area: [null, 30, 30, 30.5, 30.5],
    first: 1,
  }, DATES);
  assert.deepEqual(events.map(e => plain(e.text)), [
    'площадь 30 → 30,5 м²',
    'цена −100 000 ₽ (−2,0%), полная так же',
    'появилась в выгрузке, 5 000 000 ₽',
  ]);
});
